"""AvatarGuidance model.

Task 47. What the avatar (Aria) says about one analysis. Feeds
`avatarFeedback` in the SDS §6.5 response shape.

WHAT THE FRONTEND ACTUALLY DOES TODAY -- READ BEFORE Task 56 OR 82.

`frontend/src/components/aria/AriaGuidancePanel.jsx` does not consume this
table yet. It renders fixed per-class copy from
`frontend/src/config/ariaGuidance.js`, whose own header says:

    "Fixed educational content written for each classification... It is NOT
     generated by a model or the backend and never refers to the specific
     prompt. Task 82 will add guidance from POST /api/avatar-guide."

So right now Aria says the same thing for every Direct Jailbreak. This table
is what lets Task 82 replace that with guidance about *this* prompt. Until
then rows here are written and stored but not displayed, which is the
correct order -- the backend has to exist before the frontend can call it.

Two consequences:

  - Nothing breaks if this table is empty. Task 56 should treat guidance as
    optional in its response, exactly as it already treats sub-type.
  - The frontend's guidance object has a richer shape than `message_text`
    plus `explanation` (summary / why / nextSteps / do / dont / keyDefence).
    Task 82 will need to either flatten that into these two fields or extend
    the table. Flagged now rather than discovered then.

THREE DECISIONS:

1. analysis_id IS UNIQUE.

   One guidance message per analysis. Re-generating should update the row,
   not append a second one the API would have to choose between -- the same
   rule as SafeSuggestion.

2. message_text AND explanation ARE BOTH REQUIRED.

   message_text is what Aria says; explanation is why it matters. A guidance
   row with only the first is a notification, not teaching -- and teaching
   is the stated purpose of the avatar in the project title.

3. displayed_at IS NULLABLE AND IS NOT A CREATION TIMESTAMP.

   The plan names it `displayed_at`, not `created_at`. Those differ: it is
   written when the message actually reaches the user, so a row with NULL
   means "generated but never shown". That distinction is worth keeping --
   it answers whether users are reading the guidance at all, which the
   Tasks 60-63 analytics would otherwise be unable to tell.

   `generated_at` records creation separately.
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.analysis import AnalysisResult


class AvatarGuidance(Base):
    """One guidance message from the avatar about an analysis."""

    __tablename__ = "avatar_guidance"

    guidance_id: Mapped[int] = mapped_column(primary_key=True)

    # Unique -- see decision 1.
    analysis_id: Mapped[int] = mapped_column(
        ForeignKey("analysis_results.analysis_id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )

    # What Aria says. Required -- see decision 2.
    message_text: Mapped[str] = mapped_column(Text, nullable=False)

    # Why it matters. Also required: the avatar exists to teach.
    explanation: Mapped[str] = mapped_column(Text, nullable=False)

    # When the row was created.
    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # When it actually reached the user. NULL means generated but never
    # shown -- see decision 3.
    displayed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    analysis: Mapped["AnalysisResult"] = relationship(
        "AnalysisResult", back_populates="guidance"
    )

    @property
    def was_displayed(self) -> bool:
        """False while the guidance has been generated but not yet shown."""
        return self.displayed_at is not None

    def mark_displayed(self) -> None:
        """Stamp the moment the user actually saw this.

        Called by the endpoint that serves the guidance, not by whatever
        creates it.
        """
        if self.displayed_at is None:
            self.displayed_at = datetime.now()

    def __repr__(self) -> str:
        return (
            f"AvatarGuidance(guidance_id={self.guidance_id}, "
            f"analysis_id={self.analysis_id}, "
            f"displayed={self.was_displayed})"
        )
